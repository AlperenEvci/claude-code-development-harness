def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def slugify(value: Any) -> str:
    text = str(value or "").strip().lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-") or "project"


def component_name(value: Any) -> str:
    name = slugify(value)
    return name if name.startswith("harness-") else f"harness-{name}"


def frontmatter(text: str) -> dict[str, Any] | None:
    """Parse the limited top-level YAML shape generated by this project.

    We only need key presence and scalar/list values. This is not a general YAML
    parser and deliberately avoids adding a runtime dependency.
    """

    match = FRONTMATTER.search(text)
    if not match:
        return None

    result: dict[str, Any] = {}
    current_list: str | None = None
    for raw in match.group(1).splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith(("  - ", "\t- ")) and current_list:
            value = raw.split("-", 1)[1].strip()
            try:
                parsed = json.loads(value)
            except json.JSONDecodeError:
                parsed = value
            result.setdefault(current_list, []).append(parsed)
            continue
        if raw.startswith((" ", "\t")) or ":" not in raw:
            current_list = None
            continue
        key, raw_value = raw.split(":", 1)
        key = key.strip()
        raw_value = raw_value.strip()
        if not raw_value:
            result[key] = []
            current_list = key
            continue
        current_list = None
        if raw_value in {"true", "false"}:
            result[key] = raw_value == "true"
        else:
            try:
                result[key] = json.loads(raw_value)
            except json.JSONDecodeError:
                result[key] = raw_value
    return result


def executable_code_blocks(text: str) -> list[str]:
    """Return shell-like fenced blocks that can encode executable defaults.

    Safety tokens may legitimately appear in explanatory prose such as
    "do not use --skip-git-repo-check". The validator therefore inspects
    executable shell fences rather than treating a documented prohibition as
    an unsafe default.
    """

    blocks: list[str] = []
    for match in FENCED_BLOCK.finditer(text):
        language = match.group(1).strip().lower()
        if language in {"", "bash", "sh", "shell", "zsh"}:
            blocks.append(match.group(2))
    return blocks


def read_json(path: Path, errors: list[str], label: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        errors.append(f"invalid {label}: {exc}")
        return {}
    if not isinstance(value, dict):
        errors.append(f"{label} must be a JSON object")
        return {}
    return value


def expected_dynamic_paths(profile: dict[str, Any], errors: list[str]) -> list[str]:
    paths: list[str] = []
    for key, base, suffix in (
        ("scoped_rules", ".claude/rules", ".md"),
        ("additional_skills", ".claude/skills", "/SKILL.md"),
        ("additional_agents", ".claude/agents", ".md"),
    ):
        items = profile.get(key, [])
        if not isinstance(items, list):
            errors.append(f"profile field {key} must be an array")
            continue
        for index, item in enumerate(items):
            if not isinstance(item, dict):
                errors.append(f"profile field {key}[{index}] must be an object")
                continue
            name = component_name(item.get("name"))
            paths.append(f"{base}/{name}{suffix}")
    return paths


def format_tokens(value: int) -> str:
    if value >= 1000 and value % 1000 == 0:
        return f"{value // 1000}k"
    return str(value)


SHADOW_STUB_DIRS = {"system32", "windowsapps"}


def is_shadow_stub(path: str) -> bool:
    """True for a Windows shim that shadows the real tool.

    `System32\\bash.exe` is the WSL launcher and `WindowsApps\\python3.exe` is a
    Microsoft Store alias. Windows resolves a bare command name through System32
    before PATH, so these win even when the real tool sits earlier on PATH. The
    separator is matched on both slashes so the classification is testable from
    any host.
    """
    parts = re.split(r"[\\/]", str(path).lower())
    return bool(SHADOW_STUB_DIRS.intersection(parts))


def find_bash() -> str | None:
    """Resolve a real bash, or None.

    Returns an absolute path, because passing the bare name `bash` to
    subprocess reaches the WSL launcher on Windows. A machine whose only WSL
    distribution lacks /bin/bash then fails in a way that reads like a shell
    syntax error in the file being checked.
    """
    found = shutil.which("bash")
    if found is not None and not is_shadow_stub(found):
        return found
    if sys.platform != "win32":
        return None

    candidates: list[Path] = []
    git = shutil.which("git")
    if git is not None:
        # <root>/cmd/git.exe and <root>/mingw64/bin/git.exe both sit two levels
        # below a Git for Windows root that carries bin/bash.exe.
        root = Path(git).resolve().parent.parent
        candidates += [root / "bin" / "bash.exe", root.parent / "bin" / "bash.exe"]
    candidates += [
        Path(r"C:\Program Files\Git\bin\bash.exe"),
        Path(r"C:\Program Files (x86)\Git\bin\bash.exe"),
    ]
    for candidate in candidates:
        if candidate.is_file():
            return str(candidate)
    return None


def frontmatter_list(text: str, key: str) -> list[str] | None:
    """Return a YAML block-sequence frontmatter value, or None when absent."""
    match = re.search(
        rf"^{re.escape(key)}:[ \t]*\n((?:[ \t]*-[ \t]*\S+[ \t]*\n)+)",
        text,
        re.MULTILINE,
    )
    if match is None:
        return None
    return [line.strip().lstrip("-").strip() for line in match.group(1).splitlines()]


