#!/usr/bin/env python3
"""Validate a rendered development harness package.

The validator is intentionally dependency-free. It checks package integrity,
required files, generated Claude component frontmatter, unsafe defaults, and
installer syntax. It does not execute the generated installer or any agent.
"""

from __future__ import annotations

import argparse
import hashlib
import json
import re
import subprocess
import sys
from pathlib import Path
from typing import Any

PLACEHOLDER = re.compile(r"\{\{[a-zA-Z0-9_]+\}\}")
FRONTMATTER = re.compile(r"\A---\s*\n(.*?)\n---\s*\n", re.DOTALL)
FENCED_BLOCK = re.compile(r"```([^\n]*)\n(.*?)```", re.DOTALL)
GENERATION_MARKER = ".development-harness-generated.json"
FORBIDDEN_CODEX_DEFAULTS = (
    "--dangerously-bypass-approvals-and-sandbox",
    "--dangerously-skip-permissions",
    "--skip-git-repo-check",
    "danger-full-access",
)


def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for chunk in iter(lambda: handle.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def slugify(value: Any) -> str:
    text = str(value or "").strip().lower()
    text = re.sub(r"[^a-z0-9]+", "-", text)
    return text.strip("-") or "project"


def component_name(value: Any) -> str:
    name = slugify(value)
    return name if name.startswith("harness-") else f"harness-{name}"


def frontmatter(text: str) -> dict[str, Any] | None:
    """Parse the limited top-level YAML shape generated by this project.

    We only need key presence and scalar/list values. This is not a general YAML
    parser and deliberately avoids adding a runtime dependency.
    """

    match = FRONTMATTER.search(text)
    if not match:
        return None

    result: dict[str, Any] = {}
    current_list: str | None = None
    for raw in match.group(1).splitlines():
        if not raw.strip() or raw.lstrip().startswith("#"):
            continue
        if raw.startswith(("  - ", "\t- ")) and current_list:
            value = raw.split("-", 1)[1].strip()
            try:
                parsed = json.loads(value)
            except json.JSONDecodeError:
                parsed = value
            result.setdefault(current_list, []).append(parsed)
            continue
        if raw.startswith((" ", "\t")) or ":" not in raw:
            current_list = None
            continue
        key, raw_value = raw.split(":", 1)
        key = key.strip()
        raw_value = raw_value.strip()
        if not raw_value:
            result[key] = []
            current_list = key
            continue
        current_list = None
        if raw_value in {"true", "false"}:
            result[key] = raw_value == "true"
        else:
            try:
                result[key] = json.loads(raw_value)
            except json.JSONDecodeError:
                result[key] = raw_value
    return result


def executable_code_blocks(text: str) -> list[str]:
    """Return shell-like fenced blocks that can encode executable defaults.

    Safety tokens may legitimately appear in explanatory prose such as
    "do not use --skip-git-repo-check". The validator therefore inspects
    executable shell fences rather than treating a documented prohibition as
    an unsafe default.
    """

    blocks: list[str] = []
    for match in FENCED_BLOCK.finditer(text):
        language = match.group(1).strip().lower()
        if language in {"", "bash", "sh", "shell", "zsh"}:
            blocks.append(match.group(2))
    return blocks


def read_json(path: Path, errors: list[str], label: str) -> dict[str, Any]:
    try:
        value = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        errors.append(f"invalid {label}: {exc}")
        return {}
    if not isinstance(value, dict):
        errors.append(f"{label} must be a JSON object")
        return {}
    return value


def expected_dynamic_paths(profile: dict[str, Any], errors: list[str]) -> list[str]:
    paths: list[str] = []
    for key, base, suffix in (
        ("scoped_rules", ".claude/rules", ".md"),
        ("additional_skills", ".claude/skills", "/SKILL.md"),
        ("additional_agents", ".claude/agents", ".md"),
    ):
        items = profile.get(key, [])
        if not isinstance(items, list):
            errors.append(f"profile field {key} must be an array")
            continue
        for index, item in enumerate(items):
            if not isinstance(item, dict):
                errors.append(f"profile field {key}[{index}] must be an object")
                continue
            name = component_name(item.get("name"))
            paths.append(f"{base}/{name}{suffix}")
    return paths


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("package", type=Path)
    args = parser.parse_args()

    package_arg = args.package.expanduser()
    errors: list[str] = []
    warnings: list[str] = []

    if package_arg.is_symlink():
        errors.append(f"package path may not be a symlink: {package_arg}")
    package = package_arg.resolve()

    required_package = (
        GENERATION_MARKER,
        "payload",
        "project-profile.json",
        "harness-manifest.json",
        "install-harness.sh",
        "README.md",
    )
    for required in required_package:
        if not (package / required).exists():
            errors.append(f"missing {required}")

    if errors:
        for item in errors:
            print(f"ERROR: {item}", file=sys.stderr)
        raise SystemExit(1)

    marker = read_json(package / GENERATION_MARKER, errors, "generation marker")
    if marker.get("generator") != "development-harness":
        errors.append("generation marker does not identify development-harness")

    profile = read_json(package / "project-profile.json", errors, "project-profile.json")
    manifest = read_json(package / "harness-manifest.json", errors, "harness-manifest.json")
    payload = package / "payload"
    if payload.is_symlink() or not payload.is_dir():
        errors.append("payload must be a real directory, not a symlink")

    delegate = str(profile.get("implementation_delegate", "codex-cli")).lower()

    required_payload = [
        "AGENTS.md",
        "CLAUDE.md",
        ".claude/skills/harness-orchestration/SKILL.md",
        ".ai/README.md",
        ".ai/backlog.md",
        ".ai/templates/report.md",
        ".ai/templates/decision.md",
        ".ai/templates/spec.md",
        ".ai/harness/project-profile.json",
        "docs/ai-harness/README.md",
    ]
    tier = str(profile.get("harness_tier", "")).lower()
    mode = str(profile.get("harness_mode", "adopt")).lower()
    greenfield = profile.get("greenfield_context")

    if mode == "create":
        if tier == "fleet":
            errors.append("greenfield create mode may not start at Fleet tier")
        if not isinstance(greenfield, dict):
            errors.append("greenfield create mode requires greenfield_context")
            greenfield = {}
        required_payload += [
            ".ai/project/brief.md",
            ".ai/project/architecture.md",
            ".ai/project/roadmap.md",
            ".ai/project/open-questions.md",
        ]
        if isinstance(greenfield, dict) and greenfield.get("create_root_readme", True):
            required_payload.append("README.md")
        if isinstance(greenfield, dict) and greenfield.get("setup_depth") == "ready-to-build":
            required_payload.append(".ai/specs/current-task.md")
            blocking = greenfield.get("blocking_questions", [])
            if blocking:
                errors.append("ready-to-build greenfield package contains blocking questions")

    if delegate != "claude-only":
        required_payload.append(".claude/skills/harness-codex-delegate/SKILL.md")
    if tier in {"standard", "fleet"}:
        required_payload += [
            ".claude/agents/harness-codebase-researcher.md",
            ".claude/agents/harness-code-reviewer.md",
        ]
    if tier == "fleet":
        if delegate != "codex-cli":
            errors.append("fleet harness requires implementation_delegate=codex-cli")
        required_payload += [
            ".claude/skills/harness-codex-fleet/SKILL.md",
            ".ai/templates/lane-brief.md",
            ".ai/templates/ledger.md",
            "scripts/ai-harness/create-lane-worktree.sh",
        ]
    required_payload += expected_dynamic_paths(profile, errors)

    for rel in required_payload:
        if not (payload / rel).is_file():
            errors.append(f"missing payload file: {rel}")

    installed_profile = payload / ".ai/harness/project-profile.json"
    if installed_profile.is_file():
        installed_data = read_json(installed_profile, errors, "installed project profile")
        if installed_data != profile:
            errors.append("installed project profile does not match package project-profile.json")

    if mode == "create":
        brief = payload / ".ai/project/brief.md"
        architecture = payload / ".ai/project/architecture.md"
        for path, required_fragment in (
            (brief, "## Problem statement"),
            (architecture, "## Evidence rule"),
        ):
            if path.is_file() and required_fragment not in path.read_text(encoding="utf-8"):
                errors.append(
                    f"greenfield context file missing required section {required_fragment!r}: "
                    f"{path.relative_to(payload)}"
                )

    symlinks = [path for path in package.rglob("*") if path.is_symlink()]
    for path in symlinks:
        errors.append(f"generated package may not contain symlinks: {path.relative_to(package)}")

    actual_files = {
        str(path.relative_to(payload)): path
        for path in payload.rglob("*")
        if path.is_file() and not path.is_symlink()
    }
    manifest_entries = manifest.get("files", [])
    if not isinstance(manifest_entries, list):
        errors.append("manifest files must be an array")
        manifest_entries = []
    manifest_files: dict[str, dict[str, Any]] = {}
    for index, item in enumerate(manifest_entries):
        if not isinstance(item, dict) or not isinstance(item.get("path"), str):
            errors.append(f"invalid manifest files[{index}] entry")
            continue
        rel = item["path"]
        if rel in manifest_files:
            errors.append(f"duplicate manifest path: {rel}")
        manifest_files[rel] = item

    if set(actual_files) != set(manifest_files):
        absent_manifest = sorted(set(actual_files) - set(manifest_files))
        absent_disk = sorted(set(manifest_files) - set(actual_files))
        if absent_manifest:
            errors.append(f"files absent from manifest: {absent_manifest}")
        if absent_disk:
            errors.append(f"manifest files absent from disk: {absent_disk}")

    component_names: dict[str, str] = {}
    for rel, path in actual_files.items():
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            text = ""
        if text and PLACEHOLDER.search(text):
            errors.append(f"unresolved placeholder in {rel}")

        item = manifest_files.get(rel)
        if item:
            if item.get("sha256") != sha256(path):
                errors.append(f"hash mismatch for {rel}")
            if item.get("bytes") != path.stat().st_size:
                errors.append(f"byte-count mismatch for {rel}")

        if rel.startswith(".claude/skills/") and rel.endswith("/SKILL.md"):
            fm = frontmatter(text)
            if fm is None:
                errors.append(f"skill missing YAML frontmatter: {rel}")
                continue
            for key in ("name", "description"):
                if not fm.get(key):
                    errors.append(f"skill missing {key} frontmatter: {rel}")
            name = str(fm.get("name", ""))
            expected_name = Path(rel).parent.name
            if name and name != expected_name:
                errors.append(f"skill name/path mismatch in {rel}: {name!r} != {expected_name!r}")
            if name in component_names:
                errors.append(f"duplicate Claude component name {name!r}: {component_names[name]} and {rel}")
            elif name:
                component_names[name] = rel
            executable_text = "\n".join(executable_code_blocks(text))
            for token in FORBIDDEN_CODEX_DEFAULTS:
                if token in executable_text:
                    errors.append(f"unsafe Codex default token in executable block {rel}: {token}")

        if rel.startswith(".claude/agents/") and rel.endswith(".md"):
            fm = frontmatter(text)
            if fm is None:
                errors.append(f"agent missing YAML frontmatter: {rel}")
                continue
            for key in ("name", "description"):
                if not fm.get(key):
                    errors.append(f"agent missing {key} frontmatter: {rel}")
            name = str(fm.get("name", ""))
            expected_name = Path(rel).stem
            if name and name != expected_name:
                errors.append(f"agent name/path mismatch in {rel}: {name!r} != {expected_name!r}")
            if name in component_names:
                errors.append(f"duplicate Claude component name {name!r}: {component_names[name]} and {rel}")
            elif name:
                component_names[name] = rel
            if fm.get("permissionMode") == "bypassPermissions":
                errors.append(f"agent defaults to bypassPermissions: {rel}")

        if rel.startswith(".claude/rules/") and rel.endswith(".md"):
            fm = frontmatter(text)
            if fm is None or not fm.get("paths"):
                errors.append(f"scoped rule missing non-empty paths frontmatter: {rel}")

    # Re-check the privilege boundary of profile-generated components so a
    # modified staging package cannot smuggle broader permissions past render.
    for item in profile.get("additional_skills", []):
        if not isinstance(item, dict):
            continue
        name = component_name(item.get("name"))
        rel = f".claude/skills/{name}/SKILL.md"
        path = payload / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        fm = frontmatter(text) or {}
        if "allowed-tools" in fm:
            errors.append(f"generated project skill pre-approves tools: {rel}")
        if item.get("manual_only", True) and fm.get("disable-model-invocation") is not True:
            errors.append(f"manual generated project skill is model-invocable: {rel}")

    for item in profile.get("additional_agents", []):
        if not isinstance(item, dict):
            continue
        name = component_name(item.get("name"))
        rel = f".claude/agents/{name}.md"
        path = payload / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        required_fragments = (
            "tools:\n  - Read\n  - Grep\n  - Glob",
            "disallowedTools:\n  - Write\n  - Edit\n  - Bash",
            "permissionMode: plan",
        )
        if any(fragment not in text for fragment in required_fragments):
            errors.append(f"generated domain agent is not read-only: {rel}")

    codex_rel = ".claude/skills/harness-codex-delegate/SKILL.md"
    codex_path = payload / codex_rel
    codex_text = codex_path.read_text(encoding="utf-8") if codex_path.is_file() else ""
    if delegate == "claude-only":
        if codex_path.exists():
            errors.append("claude-only harness must omit the Codex delegate skill")
    elif delegate == "codex-plugin":
        for required_fragment in (
            "Configured transport: `codex-plugin`",
            "codex:codex-rescue",
            "openai/codex-plugin-cc",
        ):
            if required_fragment not in codex_text:
                errors.append(
                    f"official Codex plugin delegate missing {required_fragment!r}: {codex_rel}"
                )
    elif delegate == "codex-cli":
        for required_fragment in (
            "Configured transport: `codex-cli`",
            "codex exec",
            '- < "${CLAUDE_PROJECT_DIR}/.ai/specs/current-task.md"',
        ):
            if required_fragment not in codex_text:
                errors.append(
                    f"Codex CLI delegate missing {required_fragment!r}: {codex_rel}"
                )
        if "$(cat" in codex_text:
            errors.append("Codex CLI delegate must pass the spec through stdin, not shell substitution")

    install = package / "install-harness.sh"
    if not (install.stat().st_mode & 0o111):
        warnings.append("install-harness.sh is not executable")
    shell_check = subprocess.run(
        ["bash", "-n", str(install)],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if shell_check.returncode != 0:
        errors.append(f"install-harness.sh syntax error: {shell_check.stderr.strip()}")

    if tier == "fleet":
        helper = payload / "scripts/ai-harness/create-lane-worktree.sh"
        if helper.is_file() and not (helper.stat().st_mode & 0o111):
            warnings.append("fleet worktree helper is not executable")

    for rel in ("AGENTS.md", "CLAUDE.md"):
        path = payload / rel
        if path.is_file():
            line_count = path.read_text(encoding="utf-8").count("\n") + 1
            if line_count > 220:
                warnings.append(f"{rel} has {line_count} lines; always-loaded context may be too large")

    for item in warnings:
        print(f"WARNING: {item}", file=sys.stderr)
    for item in errors:
        print(f"ERROR: {item}", file=sys.stderr)

    if errors:
        raise SystemExit(1)

    print(
        f"OK: {profile.get('project_name')} "
        f"({tier}) with {len(actual_files)} payload files"
    )


if __name__ == "__main__":
    main()
