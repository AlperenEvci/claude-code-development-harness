#: The hook scripts a `guarded` package installs. A separate copy from the
#: renderer's, for the same reason `SESSION_TOOL_SCRIPTS` keeps one: a validator
#: that imports the thing it validates checks that the renderer agrees with
#: itself. A test pins the two lists together.
HOOK_SCRIPTS = ("hook_guard.py", "hook_session_start.py", "hook_precompact.py", "hook_stop.py")

HOOK_CAPABLE_TIERS = frozenset({"standard", "fleet"})


def default_hooks_policy(tier: str) -> str:
    """Mirrors `render_harness.default_hooks_policy`, a separate copy on purpose.

    The rendered profile always carries the policy the renderer resolved, so this
    decides only for a profile edited by hand after rendering. It must agree with
    the renderer: a validator that defaulted differently would pass a payload
    the renderer would have built the other way.
    """
    return "guarded" if str(tier).lower() in HOOK_CAPABLE_TIERS else "examples-only"


#: The only arguments a handler may carry after its script, and the profile key
#: each must match. A hook executes what is here, so the settings file may not
#: name a command the profile did not - that would be the settings file, which
#: an installer writes, carrying an instruction nobody reviewed in the profile.
HOOK_COMMAND_ARGS = {
    "hook_session_start.py": ("--smoke", "smoke_command"),
    "hook_stop.py": ("--check", "smallest_check_command"),
}

#: Where the rendered hook wiring lands, and the only events it may register.
#: A hook this plugin did not author is not a hook this plugin will ship.
HOOK_SETTINGS_PATH = ".claude/settings.json"
ALLOWED_HOOK_EVENTS = {"PreToolUse", "SessionStart", "PreCompact", "Stop"}

#: Seconds. A guard that can hang for the platform default of 600 would stall a
#: session on a defect rather than fail it.
MAX_HOOK_TIMEOUT = 60


def check_hooks(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
    warnings: list[str],
) -> None:
    """A generated hook must be inert unless asked for, and narrow when asked.

    The rule this file exists to keep: repository text may never widen
    authority. A hook is the sharpest possible counter-example, because it runs
    before the permission check and its decision is not the model's to argue
    with. So a rendered hook may deny and may add context, and may do nothing
    else - no allow decision, no shell string, no event this plugin did not
    author, no script that is not the byte-identical original.
    """
    policy = str(
        profile.get("hooks_policy") or default_hooks_policy(str(profile.get("harness_tier", "")))
    )
    settings = payload / ".claude" / "settings.json"
    tool_dir = payload / "scripts" / "ai-harness"
    source_dir = Path(__file__).resolve().parent

    if policy != "guarded":
        if settings.exists():
            errors.append(
                f"hooks_policy={policy} renders no hooks but {HOOK_SETTINGS_PATH} "
                "is present"
            )
        for name in HOOK_SCRIPTS:
            if (tool_dir / name).exists():
                errors.append(
                    f"hooks_policy={policy} installs no hooks but "
                    f"scripts/ai-harness/{name} is present"
                )
        return

    for name in HOOK_SCRIPTS:
        target = tool_dir / name
        if not target.is_file():
            errors.append(f"hook script missing: scripts/ai-harness/{name}")
            continue
        source = source_dir / name
        if source.is_file() and sha256(source) != sha256(target):
            errors.append(
                f"scripts/ai-harness/{name} differs from the plugin script it is "
                "copied from; a hook runs unasked, so an edited copy is an "
                "unreviewed guard"
            )
        text = target.read_text(encoding="utf-8")
        if '"allow"' in text or "permissionDecision" in text:
            errors.append(
                f"scripts/ai-harness/{name} mentions a permission decision; a "
                "generated hook may deny, never allow"
            )
        if "HARNESS_HOOKS_DISABLE" not in text:
            errors.append(
                f"scripts/ai-harness/{name} has no HARNESS_HOOKS_DISABLE escape; "
                "a hook with no way out can lock an operator out of the repository"
            )

    if not settings.is_file():
        errors.append(f"hooks_policy=guarded but {HOOK_SETTINGS_PATH} is missing")
        return

    raw = settings.read_text(encoding="utf-8")
    for token in FORBIDDEN_CODEX_DEFAULTS:
        if token in raw:
            errors.append(f"unsafe token in {HOOK_SETTINGS_PATH}: {token}")
    if "bypassPermissions" in raw:
        errors.append(
            f"{HOOK_SETTINGS_PATH} mentions bypassPermissions; generated settings "
            "may not widen permissions"
        )

    try:
        data = json.loads(raw)
    except json.JSONDecodeError as error:
        errors.append(f"{HOOK_SETTINGS_PATH} is not valid JSON: {error}")
        return
    if not isinstance(data, dict):
        errors.append(f"{HOOK_SETTINGS_PATH} must be a JSON object")
        return

    for key in data:
        if key not in {"$schema", "hooks"}:
            # Permissions, environment, and model belong to the operator. A
            # generated settings file that carried them would be the plugin
            # deciding something it was never asked to decide.
            errors.append(
                f"{HOOK_SETTINGS_PATH} sets {key}; generated settings carry hooks "
                "and nothing else"
            )

    hooks = data.get("hooks")
    if not isinstance(hooks, dict) or not hooks:
        errors.append(f"{HOOK_SETTINGS_PATH} registers no hooks")
        return

    expected_command = str(profile.get("python_command", "python3"))
    seen_scripts: set[str] = set()

    for event, groups in hooks.items():
        if event not in ALLOWED_HOOK_EVENTS:
            errors.append(
                f"{HOOK_SETTINGS_PATH} registers {event}; this generator authors "
                f"only {', '.join(sorted(ALLOWED_HOOK_EVENTS))}"
            )
            continue
        if not isinstance(groups, list):
            errors.append(f"{HOOK_SETTINGS_PATH}: {event} must be an array")
            continue
        for group in groups:
            if not isinstance(group, dict):
                errors.append(f"{HOOK_SETTINGS_PATH}: {event} entry must be an object")
                continue
            handlers = group.get("hooks")
            if not isinstance(handlers, list) or not handlers:
                errors.append(f"{HOOK_SETTINGS_PATH}: {event} entry has no handlers")
                continue
            for handler in handlers:
                if not isinstance(handler, dict):
                    errors.append(f"{HOOK_SETTINGS_PATH}: {event} handler must be an object")
                    continue
                kind = handler.get("type")
                if kind != "command":
                    # `prompt` and `agent` handlers call a model. A guard that
                    # calls a model is slow, non-deterministic, and bills the
                    # operator for every tool call.
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler type {kind!r}; only "
                        "command hooks are generated"
                    )
                    continue
                if handler.get("command") != expected_command:
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler runs "
                        f"{handler.get('command')!r}, not the profile's "
                        f"python_command {expected_command!r}"
                    )
                args = handler.get("args")
                if not isinstance(args, list) or not args:
                    # Exec form only. A shell string would put quoting, globbing,
                    # and a Windows/POSIX difference into the one file that must
                    # behave identically on both.
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler has no args; "
                        "generated hooks use exec form"
                    )
                    continue
                script = str(args[0])
                prefix = "${CLAUDE_PROJECT_DIR}/scripts/ai-harness/"
                if not script.startswith(prefix):
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler runs {script}, which "
                        f"is not under {prefix}"
                    )
                    continue
                name = script[len(prefix) :]
                if name not in HOOK_SCRIPTS:
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler runs {name}, which is "
                        "not a hook script this generator installs"
                    )
                    continue
                if not (tool_dir / name).is_file():
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler runs {name}, which is "
                        "not in the payload"
                    )
                seen_scripts.add(name)
                check_hook_args(name, [str(item) for item in args[1:]], profile, errors)
                timeout = handler.get("timeout")
                if not isinstance(timeout, int) or not 1 <= timeout <= MAX_HOOK_TIMEOUT:
                    errors.append(
                        f"{HOOK_SETTINGS_PATH}: {event} handler timeout {timeout!r} is "
                        f"not an integer between 1 and {MAX_HOOK_TIMEOUT} seconds"
                    )

    check = str(profile.get("smallest_check_command", "")).strip()
    if check and "hook_stop.py" not in seen_scripts:
        errors.append(
            f"the profile names a smallest_check_command but {HOOK_SETTINGS_PATH} "
            "registers no Stop handler, so it would never run"
        )
    if not check:
        # A Stop hook with nothing to run is not registered, by design.
        seen_scripts.add("hook_stop.py")

    missing = [name for name in HOOK_SCRIPTS if name not in seen_scripts]
    if missing:
        warnings.append(
            f"{HOOK_SETTINGS_PATH} installs {', '.join(missing)} but registers "
            "no event for it"
        )


def check_hook_args(
    name: str, extra: list[str], profile: dict[str, Any], errors: list[str]
) -> None:
    """A handler carries its script, and at most the one flag its script takes.

    The flag's value must equal the profile's command byte for byte. The hook
    runs that value through a shell, so a settings file that disagreed with the
    profile would execute something the operator never saw in the profile they
    approved.
    """
    allowed = HOOK_COMMAND_ARGS.get(name)
    if not extra:
        if allowed and str(profile.get(allowed[1], "")).strip():
            flag, key = allowed
            errors.append(
                f"{HOOK_SETTINGS_PATH}: {name} carries no {flag} but the profile "
                f"sets {key}, so the hook would never run it"
            )
        return
    if allowed is None:
        errors.append(
            f"{HOOK_SETTINGS_PATH}: {name} takes no arguments; found {extra}"
        )
        return
    flag, key = allowed
    expected = str(profile.get(key, "")).strip()
    if extra != [flag, expected] or not expected:
        errors.append(
            f"{HOOK_SETTINGS_PATH}: {name} arguments {extra} are not "
            f"[{flag!r}, the profile's {key}]; a hook may run only the command "
            "the profile names"
        )


def check_declared_tier(rel: str, text: str, errors: list[str]) -> str | None:
    """Verify an agent file grants exactly what the tier it names allows.

    Applies to every agent in the payload, not only the ones the profile
    declares, so the core harness agents and any hand-added file are held to the
    same boundary. Returns the capability it found, or None.
    """
    match = re.search(r"^capability:[ \t]*(\S+)[ \t]*$", text, re.MULTILINE)
    if match is None:
        return None

    capability = match.group(1).strip().strip("\"'")
    tier = CAPABILITY_TIERS.get(capability)
    if tier is None:
        errors.append(f"agent declares unknown capability {capability!r}: {rel}")
        return None

    # Compare the whole list, not a prefix: a substring match would accept an
    # agent that kept the tier's tools and appended Write to them.
    if frontmatter_list(text, "tools") != tier["tools"]:
        errors.append(f"agent tools do not match its {capability} tier: {rel}")

    if (frontmatter_list(text, "disallowedTools") or []) != tier["disallowed"]:
        errors.append(
            f"agent does not deny the tools its {capability} tier forbids: {rel}"
        )

    if f"permissionMode: {tier['permission_mode']}" not in text:
        errors.append(
            f"agent permission mode does not match its {capability} tier: {rel}"
        )

    if not tier["writes"]:
        # A non-writing tier that somehow acquired an edit-accepting mode is the
        # exact escalation this check exists for.
        for mode in EDIT_ACCEPTING_MODES:
            if f"permissionMode: {mode}" in text:
                errors.append(f"{capability} agent uses permission mode {mode}: {rel}")

    return capability


def check_agent_tuning(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
) -> None:
    """Every agent's model and effort must be the ones the profile resolved.

    Two different failures share this check. An `effort` outside the ladder is the
    quieter one: `claude --effort` warns on an unknown value, runs at its default,
    and exits 0, so a package can ship an effort that never takes effect and
    nothing downstream will say so. And a `model` or `effort` that simply drifted
    from the profile means the file an operator reads and the session that actually
    runs disagree, which is the same class of defect the tier check exists for.

    An agent may name its own `model` - the profile's `additional_agents` allows it -
    so the model is checked against the tier default *or* an explicitly declared one.
    `effort` has no such escape hatch and is compared to the tier's value alone.
    """
    models = profile.get("agent_models", {})
    declared_models = {
        component_name(agent.get("name")): str(agent["model"]).strip()
        for agent in profile.get("additional_agents", [])
        if isinstance(agent, dict) and "model" in agent
    }

    for path in sorted((payload / ".claude" / "agents").glob("*.md")):
        rel = f".claude/agents/{path.name}"
        text = path.read_text(encoding="utf-8")
        parsed = frontmatter(text)
        if parsed is None:
            continue
        match = re.search(r"^capability:[ \t]*(\S+)[ \t]*$", text, re.MULTILINE)
        if match is None:
            continue
        capability = match.group(1).strip().strip("\"'")
        tier = CAPABILITY_TIERS.get(capability)
        if tier is None:
            continue
        tuning = models.get(capability, {})

        effort = str(parsed.get("effort", "")).strip()
        if not effort:
            errors.append(f"agent declares no effort: {rel}")
        elif effort not in ALLOWED_EFFORT:
            errors.append(
                f"agent effort {effort!r} is not one of "
                f"{', '.join(ALLOWED_EFFORT)}, and the CLI would ignore it "
                f"without failing: {rel}"
            )
        else:
            expected_effort = str(tuning.get("effort", tier["effort"]))
            if effort != expected_effort:
                errors.append(
                    f"agent effort {effort!r} does not match the {capability} "
                    f"tier's {expected_effort!r}: {rel}"
                )

        model = str(parsed.get("model", "")).strip()
        if not model:
            errors.append(f"agent declares no model: {rel}")
            continue
        expected_model = declared_models.get(
            path.stem, str(tuning.get("model", tier["model"]))
        )
        if model != expected_model:
            errors.append(
                f"agent model {model!r} does not match the profile's "
                f"{expected_model!r}: {rel}"
            )


def check_launch_line_is_runnable(payload: Path, errors: list[str]) -> None:
    """No agent may document a launch line that names `inherit` as a model.

    `inherit` is valid in frontmatter, where it means "use the session's model",
    and invalid on the launcher, which rejects it as `unrecognized_model` - on a
    zero exit code, measured in
    `.ai/reports/0008-model-effort-and-agent-scoping.md`. The renderer already
    omits the flag through `model_effort_flags`; this check is what keeps a
    hand-edited or hand-added agent file from reintroducing it, and it is cheap
    because the failure it prevents is a session that dies at the API for a reason
    the frontmatter says is legal.
    """
    for path in sorted((payload / ".claude" / "agents").glob("*.md")):
        text = path.read_text(encoding="utf-8")
        if f"--model {MODEL_INHERIT}" in text:
            errors.append(
                "agent documents `--model inherit`, which the launcher rejects as "
                f"unrecognized_model: .claude/agents/{path.name}"
            )


def check_permission_bypass(payload: Path, errors: list[str]) -> None:
    """No generated file may put a permission-bypass flag in a runnable block.

    This used to run only over skills. The harness now generates runnable blocks
    in CLAUDE.md and in every agent file, so a bypass flag in a session launch
    line would have shipped unexamined. Prose is still exempt: a documented
    prohibition is not an unsafe default, which is why only executable fences
    are read.

    1.14 added a second file class that is executable in full rather than in
    fences. `.claude/settings.json` is configuration Claude Code acts on, so
    every byte of it is read here rather than only its code blocks.
    """
    settings = payload / ".claude" / "settings.json"
    if settings.is_file():
        try:
            settings_text = settings.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            settings_text = ""
        for token in FORBIDDEN_CODEX_DEFAULTS:
            if token in settings_text:
                errors.append(
                    f"unsafe default token in {HOOK_SETTINGS_PATH}: {token}"
                )
                break

    for path in sorted(payload.rglob("*.md")):
        rel = path.relative_to(payload).as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        executable_text = "\n".join(executable_code_blocks(text))
        for token in FORBIDDEN_CODEX_DEFAULTS:
            if token in executable_text:
                errors.append(
                    f"unsafe Codex default token in executable block {rel}: {token}"
                )
                break


def session_documentation(payload: Path) -> tuple[str, str]:
    """The always-loaded contract and the on-demand session skill, as text.

    Since 1.16.0 the session procedure is split across the two. A check that
    asks *is this reachable* reads both; a check that asks *does this hold
    without being asked for* reads only the first.
    """
    claude_md = payload / "CLAUDE.md"
    skill = payload / ".claude" / "skills" / SESSION_SKILL / "SKILL.md"
    return (
        claude_md.read_text(encoding="utf-8") if claude_md.is_file() else "",
        skill.read_text(encoding="utf-8") if skill.is_file() else "",
    )


def check_session_tools(
    profile: dict[str, Any], payload: Path, errors: list[str]
) -> None:
    """The session tooling must be installed, unmodified, and documented.

    Byte-identity matters more than presence. These scripts are copied rather
    than templated precisely so the installed copy is the one the plugin's suite
    tested; a drifted copy would be an untested variant enforcing capability
    tiers in someone else's repository.
    """
    tier = str(profile.get("harness_tier", ""))
    expected = tier in {"standard", "fleet"}
    tool_dir = payload / "scripts" / "ai-harness"
    source_dir = Path(__file__).resolve().parent

    if not expected:
        for name in SESSION_TOOL_SCRIPTS:
            if (tool_dir / name).exists():
                errors.append(
                    f"{tier} installs no session tooling but "
                    f"scripts/ai-harness/{name} is present"
                )
        return

    for name in SESSION_TOOL_SCRIPTS:
        target = tool_dir / name
        if not target.is_file():
            errors.append(f"session tooling missing: scripts/ai-harness/{name}")
            continue
        source = source_dir / name
        if source.is_file() and sha256(source) != sha256(target):
            errors.append(
                f"scripts/ai-harness/{name} differs from the plugin script it is "
                "copied from"
            )

    # Since 1.16.0 the procedure lives in the on-demand `harness-session` skill
    # and `CLAUDE.md` keeps a pointer to it. These checks ask whether an operator
    # can reach the instruction at all, so they read the pair: a recipe is as
    # documented in a skill the model loads on the situation as it was inline.
    claude_md = payload / "CLAUDE.md"
    contract, skill = session_documentation(payload)
    documented = contract + "\n" + skill

    if claude_md.is_file():
        if "## Agent sessions" not in contract:
            errors.append("CLAUDE.md is missing the `## Agent sessions` section")
        for token, message in SESSION_SAFETY_LINES:
            if token not in contract:
                # These two do not move with the procedure. A prohibition is
                # most needed by the session that never thought to ask for a
                # skill, so an on-demand load is the wrong place for it.
                errors.append(message)

    if "harness_session.py sweep" not in documented:
        # A background session outlives its invoker. A harness that never
        # states the teardown step leaves orphans by default.
        errors.append("neither CLAUDE.md nor the session skill documents the teardown sweep")
    if "read --correlation" not in documented:
        # Without the correlation id a bus is a pile of mailboxes: you can
        # read what one agent said, never what one unit of work cost. The
        # field only earns its keep if the contract says how to use it.
        errors.append(
            "neither CLAUDE.md nor the session skill documents "
            "`harness_bus.py read --correlation`"
        )
    if "harness_report.py --out" not in documented:
        # The bus, the ledger, and the checkpoints are all write paths. A
        # harness that installs the reader without naming it leaves an
        # operator reading four JSON trees by hand, which is the state this
        # script was added to end.
        errors.append("neither CLAUDE.md nor the session skill documents the harness report")
    if "come from you, not from the agent" not in documented:
        # The trace is launcher-reported by construction. A contract that
        # ships the fields without that sentence invites an agent to fill
        # them in by guessing, which is how a guess becomes a measurement.
        errors.append(
            "the trace fields are documented but not that they are launcher-reported"
        )

    ledger = payload / ".ai" / "progress.json"
    if not ledger.is_file():
        errors.append("session tooling is installed but .ai/progress.json is missing")
    else:
        try:
            data = json.loads(ledger.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as error:
            errors.append(f".ai/progress.json is not readable JSON: {error}")
        else:
            items = data.get("items") if isinstance(data, dict) else None
            if not isinstance(items, list):
                errors.append(".ai/progress.json has no `items` list")
            elif any(item.get("passes") for item in items if isinstance(item, dict)):
                # A repository that was rendered five seconds ago has proven
                # nothing. A seeded ledger claiming otherwise is a lie shipped
                # into someone else's project on day one.
                errors.append(
                    ".ai/progress.json ships an item already marked passing; a "
                    "freshly rendered ledger has proven nothing"
                )

    agents_md = payload / "AGENTS.md"
    if agents_md.is_file():
        budget = agents_md.read_text(encoding="utf-8")
        if "harness_checkpoint.py status" not in budget + skill:
            # The whole point of shipping the tool is that the band stops being
            # prose. A contract that installs it without saying how to run it
            # leaves the policy exactly as unenforceable as before. The recipe
            # moved into the skill in 1.16.0; the band itself stayed here.
            errors.append(
                "the checkpoint tool is installed but neither AGENTS.md nor the "
                "session skill documents `harness_checkpoint.py status`"
            )


def check_read_only_agents_are_not_detached(payload: Path, errors: list[str]) -> None:
    """A read-only agent must never be documented as a background session.

    `--bg` refuses `--print`, so a detached session has no structured result and
    can only report by writing a bus envelope - which a tier without `Write`
    cannot do. Telling a reader to launch detached documents a session whose
    output is unreachable.
    """
    agents_dir = payload / ".claude" / "agents"
    if not agents_dir.is_dir():
        return
    for path in sorted(agents_dir.rglob("*.md")):
        rel = path.relative_to(payload).as_posix()
        try:
            text = path.read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError):
            continue
        capability = None
        match = re.search(r"^capability:\s*(\S+)\s*$", text, re.MULTILINE)
        if match:
            capability = match.group(1).strip()
        if capability not in CAPABILITY_TIERS:
            continue
        if CAPABILITY_TIERS[capability]["writes"]:
            continue
        if "claude --bg" in text:
            errors.append(
                f"{rel} is a {capability} and cannot report from a background "
                "session, but documents `claude --bg`"
            )


def check_agent_capabilities(
    profile: dict[str, Any], payload: Path, errors: list[str]
) -> None:
    """Re-derive each generated agent's authority from its rendered file.

    Compensating control 3 from decision 0001. This replaces the v0.2 blanket
    "every generated agent is read-only" check: the tier is now what is asserted,
    so a staging package cannot be edited to widen an agent past its declared
    tier, and it cannot silently drop to a weaker one either.
    """
    for item in profile.get("additional_agents", []):
        if not isinstance(item, dict):
            continue
        name = component_name(item.get("name"))
        rel = f".claude/agents/{name}.md"
        path = payload / rel
        if not path.is_file():
            continue

        capability = str(item.get("capability", "reader")).strip().lower() or "reader"
        tier = CAPABILITY_TIERS.get(capability)
        if tier is None:
            errors.append(f"unknown capability tier {capability!r}: {rel}")
            continue

        text = path.read_text(encoding="utf-8")

        # What the tier grants is checked for every agent file as it is walked
        # above. What remains here is profile-specific: the file must name the
        # tier the profile assigned it, and an implementer must carry its scope.
        declared = re.search(r"^capability:[ \t]*(\S+)[ \t]*$", text, re.MULTILINE)
        if declared is None or declared.group(1).strip().strip("\"'") != capability:
            errors.append(
                f"agent frontmatter does not record capability {capability!r}: {rel}"
            )

        if not tier["writes"]:
            continue

        scope = item.get("writable_paths") or []
        if not scope:
            errors.append(f"implementer agent declares no writable scope: {rel}")
        for entry in scope:
            if f"`{entry}`" not in text:
                errors.append(
                    f"implementer agent omits declared writable path {entry!r}: {rel}"
                )
        if item.get("approved_by_operator") is not True:
            errors.append(
                f"implementer agent lacks recorded operator approval: {rel}"
            )


def check_line_endings(package: Path, errors: list[str]) -> None:
    """Generated files must be LF on every platform.

    A CRLF package is not cosmetic: `install-harness.sh` carries a carriage
    return into its shebang and will not run on Linux or macOS. Rendering on
    Windows produced exactly that until the renderer forced LF, so this is a
    regression gate rather than a style preference.
    """
    for path in sorted(package.rglob("*")):
        if not path.is_file() or path.is_symlink():
            continue
        try:
            raw = path.read_bytes()
        except OSError:
            continue
        if b"\r\n" in raw:
            errors.append(
                "CRLF line endings in generated file: "
                f"{path.relative_to(package).as_posix()}"
            )


def check_installer_syntax(
    package: Path, errors: list[str], warnings: list[str]
) -> None:
    """Parse the generated installer with a real bash before it is ever run."""
    install = package / "install-harness.sh"
    if not (install.stat().st_mode & 0o111):
        warnings.append("install-harness.sh is not executable")

    bash_binary = find_bash()
    if bash_binary is None:
        warnings.append(
            "bash not found; install-harness.sh was not syntax-checked. "
            "This check is enforced on CI."
        )
        return

    shell_check = subprocess.run(
        [bash_binary, "-n", str(install)],
        text=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
        check=False,
    )
    if shell_check.returncode != 0:
        errors.append(f"install-harness.sh syntax error: {shell_check.stderr.strip()}")


def workflow_syntax_error(node_binary: str, text: str) -> str:
    """Syntax-check a workflow script by wrapping it as the async body it really is.

    A workflow script legitimately ends in a top-level `return`, which is invalid
    in a standalone module, so the body is wrapped before checking.
    """
    body = text.replace("export const meta", "const meta", 1)
    wrapped = (
        "async function __workflow("
        "agent, parallel, pipeline, phase, log, args, budget, workflow) {\n"
        + body
        + "\n}\n"
    )
    with tempfile.TemporaryDirectory() as tmp:
        probe = Path(tmp) / "workflow-probe.mjs"
        probe.write_text(wrapped, encoding="utf-8")
        result = subprocess.run(
            [node_binary, "--check", str(probe)],
            text=True,
            stdout=subprocess.PIPE,
            stderr=subprocess.PIPE,
            check=False,
        )
    if result.returncode == 0:
        return ""
    for line in result.stderr.splitlines():
        if "Error" in line and "Node.js" not in line:
            return line.strip()
    return "unknown syntax error"


def check_workflows(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
    warnings: list[str],
) -> None:
    """Every declared graph must have a runnable script, and no script may be an orphan."""
    graphs = profile.get("graphs") or []
    workflow_dir = payload / ".claude" / "workflows"

    declared: dict[str, dict[str, Any]] = {}
    for graph in graphs:
        if isinstance(graph, dict) and str(graph.get("name", "")).strip():
            declared[str(graph["name"]).strip()] = graph

    present = (
        {path.stem for path in workflow_dir.glob("*.js")}
        if workflow_dir.is_dir()
        else set()
    )

    if not declared:
        if present:
            errors.append(
                ".claude/workflows contains scripts but the profile declares no graphs"
            )
        return

    if not workflow_dir.is_dir():
        errors.append("profile declares graphs but .claude/workflows is missing")
        return

    for name in sorted(set(declared) - present):
        errors.append(f"graph {name!r} has no generated workflow script")
    for name in sorted(present - set(declared)):
        errors.append(
            f".claude/workflows/{name}.js does not correspond to a declared graph"
        )

    node_binary = shutil.which("node")
    if node_binary is None:
        warnings.append(
            "node not found; generated workflow scripts were not syntax-checked"
        )

    for name in sorted(set(declared) & present):
        text = (workflow_dir / f"{name}.js").read_text(encoding="utf-8")

        if "export const meta" not in text:
            errors.append(f"{name}.js is missing the required meta block")

        # A loop that lost its cap could run without bound.
        for node_spec in declared[name].get("nodes", []):
            if not isinstance(node_spec, dict):
                continue
            cap = node_spec.get("max_iterations")
            if cap is None:
                continue
            if f"while (attempt < {cap})" not in text:
                errors.append(
                    f"{name}.js lost the iteration cap for node "
                    f"{node_spec.get('id')!r}"
                )

        if node_binary is not None:
            syntax_error = workflow_syntax_error(node_binary, text)
            if syntax_error:
                errors.append(f"{name}.js is not valid JavaScript: {syntax_error}")


def hosts_of(profile: dict[str, Any]) -> list[str]:
    value = profile.get("hosts")
    if isinstance(value, list) and value:
        return [str(item).strip().lower() for item in value]
    return list(DEFAULT_HOSTS)


def check_hosts(profile: dict[str, Any], errors: list[str]) -> None:
    """The declared hosts must be a known, deduplicated set including Claude Code."""
    value = profile.get("hosts")
    if value is None:
        return
    if not isinstance(value, list) or not value:
        errors.append("hosts must be a non-empty array of host names")
        return
    names = [str(item).strip().lower() for item in value]
    for name in names:
        if name not in ALLOWED_HOSTS:
            errors.append(f"unknown host in profile: {name!r}")
    if len(set(names)) != len(names):
        errors.append("hosts lists the same host twice")
    if "claude-code" not in names:
        errors.append("hosts must include claude-code; the package always renders it")


def check_codex_contract_size(
    profile: dict[str, Any], payload: Path, errors: list[str], warnings: list[str]
) -> None:
    """On a Codex host, `AGENTS.md` past the byte cap is a truncated contract.

    Claude Code and OpenCode have no such cap, so this is reported only for the
    host that has one, and it is measured in bytes because that is the unit
    `project_doc_max_bytes` counts.
    """
    agents = payload / "AGENTS.md"
    if "codex" not in hosts_of(profile) or not agents.is_file():
        return
    size = agents.stat().st_size
    if size >= CODEX_DOC_MAX_BYTES:
        errors.append(
            f"AGENTS.md is {size} bytes and this profile declares a codex host; "
            f"Codex reads at most {CODEX_DOC_MAX_BYTES} bytes of the AGENTS.md "
            "hierarchy, so the rest of the contract would be silently dropped"
        )
    elif size > CODEX_DOC_MAX_BYTES * 3 // 4:
        warnings.append(
            f"AGENTS.md is {size} bytes, within a quarter of the Codex "
            f"{CODEX_DOC_MAX_BYTES}-byte cap on the AGENTS.md hierarchy"
        )


def check_codex_skill_mirror(
    profile: dict[str, Any], payload: Path, errors: list[str]
) -> None:
    """`.agents/skills/` exists exactly when a Codex host is declared, byte for byte.

    Same rule as the runtime scripts: a copy that is not identical to the file
    the suite tested is an untested variant, and here it would be one the two
    hosts disagree about, which is worse than an absent file.
    """
    source_root = payload / ".claude" / "skills"
    mirror_root = payload / ".agents" / "skills"
    declared = "codex" in hosts_of(profile)

    if not declared:
        if mirror_root.exists():
            errors.append(
                "no codex host is declared but .agents/skills/ is present; it "
                "would be a second copy of every skill that nothing keeps current"
            )
        return

    if not mirror_root.is_dir():
        errors.append(
            "profile declares a codex host but .agents/skills/ is missing; "
            "Codex reads that path and never reads .claude/skills/"
        )
        return

    expected = {
        path.relative_to(source_root).as_posix()
        for path in source_root.rglob("*")
        if path.is_file()
    }
    actual = {
        path.relative_to(mirror_root).as_posix()
        for path in mirror_root.rglob("*")
        if path.is_file()
    }
    for rel in sorted(expected - actual):
        errors.append(f"codex skill mirror is missing .agents/skills/{rel}")
    for rel in sorted(actual - expected):
        errors.append(
            f".agents/skills/{rel} has no counterpart under .claude/skills/; "
            "the mirror is a copy, not a place to add files"
        )
    for rel in sorted(expected & actual):
        if sha256(source_root / rel) != sha256(mirror_root / rel):
            errors.append(
                f".agents/skills/{rel} differs from .claude/skills/{rel}; the "
                "two hosts would read different instructions from one harness"
            )


def check_always_loaded_size(payload: Path, errors: list[str]) -> None:
    """Measure the contract that loads on every session and fail it if it is big.

    `CLAUDE.md` imports `AGENTS.md`, and an `@import` loads at launch, so the
    always-loaded contract is the sum of the two, not either alone. The
    platform's stated target is under 200 lines, and since 1.16.0 crossing it
    fails the package. The count prints even when it passes, because the number
    is what makes the next contract addition a decision rather than an accident.
    """
    loaded: dict[str, int] = {}
    for rel in ("CLAUDE.md", "AGENTS.md"):
        path = payload / rel
        if path.is_file():
            loaded[rel] = path.read_text(encoding="utf-8").count("\n") + 1
    if not loaded:
        return
    total = sum(loaded.values())
    parts = " + ".join(f"{rel} {count}" for rel, count in loaded.items())
    print(
        f"INFO: always-loaded contract is {total} lines ({parts}); "
        f"target is under {ALWAYS_LOADED_LINE_TARGET}",
        file=sys.stderr,
    )
    if total >= ALWAYS_LOADED_LINE_TARGET:
        errors.append(
            f"always-loaded contract is {total} lines ({parts}); the platform "
            f"target is under {ALWAYS_LOADED_LINE_TARGET}. Move procedure into "
            "an on-demand skill rather than trimming the rules: what is left "
            "in the contract is what holds in a session that never thinks to "
            "ask for it"
        )


def check_model_invocable_skills(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
    warnings: list[str],
) -> None:
    """A skill the harness depends on must be one the model can actually open.

    This is the invariant with the quietest failure. `disable-model-invocation`
    is a legitimate flag - profile-declared `additional_skills` default to it,
    because an operator adding a procedure means to invoke it themselves. On a
    skill the harness routes through, it is a deletion that leaves the file in
    place, and nothing about the rendered package would otherwise look wrong.
    """
    for name in MODEL_INVOCABLE_SKILLS:
        path = payload / ".claude" / "skills" / name / "SKILL.md"
        if not path.is_file():
            continue
        match = FRONTMATTER.match(path.read_text(encoding="utf-8"))
        if match is None:
            errors.append(f"{name}/SKILL.md has no frontmatter")
            continue
        for line in match.group(1).splitlines():
            key, _, value = line.partition(":")
            if key.strip() != "disable-model-invocation":
                continue
            if value.strip().lower() in {"true", "yes", "on"}:
                errors.append(
                    f"{name}/SKILL.md sets disable-model-invocation, which makes it "
                    "unreachable to the model; the harness routes through this skill"
                )


def check_important_paths_rule(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
    warnings: list[str],
) -> None:
    """The map stays in the contract; the detail moves to a rule that must exist.

    Splitting a section across two files is the kind of change that half-lands:
    the contract loses its descriptions, the rule is not written, and nothing is
    obviously broken because both files still parse. What is lost is the answer to
    "what is this directory for", and it is lost silently.

    A path-scoped rule is also the one artifact class whose failure mode is
    silence. A malformed matcher does not error; the rule simply never loads. So
    the frontmatter is checked against the profile rather than trusted.
    """
    paths = [str(item).strip() for item in profile.get("important_paths", []) if str(item).strip()]
    rule = payload / ".claude" / "rules" / f"{IMPORTANT_PATHS_RULE}.md"
    agents = payload / "AGENTS.md"

    expected = important_path_globs(profile)
    described = sum(
        len(description)
        for _, description in (split_important_path(entry) for entry in paths)
        if description
    )
    if not expected or described < IMPORTANT_PATHS_SPLIT_CHARS:
        if rule.is_file():
            errors.append(
                f"{IMPORTANT_PATHS_RULE}.md was rendered for a profile whose "
                "important-path list is short enough to stay whole in AGENTS.md, or "
                "has no globbable path at all; either way the rule costs more than "
                "it saves"
            )
        return

    if not rule.is_file():
        errors.append(
            f".claude/rules/{IMPORTANT_PATHS_RULE}.md is missing; AGENTS.md points "
            "at it for what each important path is for"
        )
        return

    text = rule.read_text(encoding="utf-8")
    if not text.startswith("---\npaths:\n"):
        errors.append(
            f"{IMPORTANT_PATHS_RULE}.md must open with `paths:` frontmatter, or it "
            "loads for every session instead of the ones that touch these paths"
        )
    for glob in expected:
        if f'"{glob}"' not in text:
            errors.append(
                f"{IMPORTANT_PATHS_RULE}.md does not scope {glob!r}, which the "
                "profile lists as an important path"
            )
    for entry in paths:
        path, description = split_important_path(entry)
        if path is not None and description and description not in text:
            errors.append(
                f"{IMPORTANT_PATHS_RULE}.md dropped the description of {path!r}; "
                "it left AGENTS.md and has to land somewhere"
            )

    if agents.is_file():
        contract = agents.read_text(encoding="utf-8")
        if f".claude/rules/{IMPORTANT_PATHS_RULE}.md" not in contract:
            errors.append(
                "AGENTS.md keeps the important-path names but no longer says where "
                "their descriptions went"
            )
        for entry in paths:
            path, _ = split_important_path(entry)
            if path is not None and f"`{path}`" not in contract:
                errors.append(
                    f"AGENTS.md no longer names the important path {path!r}; the map "
                    "stays in the always-loaded contract even though the detail moved"
                )


def check_context_policy(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
    warnings: list[str],
) -> None:
    """The context budget is a safety-relevant contract, so verify it survived rendering."""
    policy = profile.get("context_policy")
    if not isinstance(policy, dict):
        errors.append("project-profile.json is missing a normalized context_policy object")
        return

    band = policy.get("working_band")
    if not isinstance(band, dict):
        errors.append("context_policy.working_band must be an object")
        return

    floor = band.get("floor_tokens")
    ceiling = band.get("ceiling_tokens")
    for label, value in (("floor_tokens", floor), ("ceiling_tokens", ceiling)):
        if isinstance(value, bool) or not isinstance(value, int):
            errors.append(f"context_policy.working_band.{label} must be an integer")
            return
    if floor >= ceiling:
        errors.append("context_policy.working_band.floor_tokens must be below ceiling_tokens")
        return

    # Since 1.15.0 `harness_session.py` passes the ceiling to `claude --autocompact`,
    # which refuses anything outside 100k-1M at argument parsing. A package that
    # validated with a ceiling outside that range would install cleanly and then be
    # unable to open a session, so the range is checked here as well as in the
    # renderer: this is the gate a package passes through, and the renderer is not
    # the only thing that can produce one.
    if ceiling < AUTOCOMPACT_MIN_TOKENS or ceiling > AUTOCOMPACT_MAX_TOKENS:
        errors.append(
            "context_policy.working_band.ceiling_tokens must be between "
            f"{AUTOCOMPACT_MIN_TOKENS} and {AUTOCOMPACT_MAX_TOKENS}: it is passed "
            "to `claude --autocompact`, which refuses anything outside that range"
        )

    if str(policy.get("on_ceiling", "")) not in ALLOWED_CEILING_ACTIONS:
        errors.append(
            f"context_policy.on_ceiling must be one of {sorted(ALLOWED_CEILING_ACTIONS)}"
        )

    expected_band = f"{format_tokens(floor)}-{format_tokens(ceiling)} tokens"

    agents = payload / "AGENTS.md"
    if agents.is_file():
        text = agents.read_text(encoding="utf-8")
        if "## Context budget" not in text:
            errors.append("AGENTS.md is missing the Context budget section")
        elif expected_band not in text:
            errors.append(
                f"AGENTS.md does not state the configured working band {expected_band!r}"
            )

        # 2.1.0 moved the discipline out of `CLAUDE.md`, which only Claude Code
        # reads, into the one file every host loads. Both sections are checked
        # on the same text for that reason.
        if "## Context discipline" not in text:
            errors.append("AGENTS.md is missing the Context discipline section")


ORCA_SECTION = "### Watching a session in Orca"

#: Rules the rendered Orca guidance must carry. Each one is a property the
#: launcher enforces in code; a harness that documents the surface without them
#: would invite an operator to reach for Orca's own agent launcher, which takes
#: no tier flags.
ORCA_REQUIRED_CLAUSES = (
    "--lane",
    "orca worktree create --agent claude",
    "never parsed",
)


def check_session_surface(
    profile: dict[str, Any],
    payload: Path,
    errors: list[str],
    warnings: list[str],
) -> None:
    """The launch surface decides how sessions get started, so verify it rendered.

    Drift in either direction is a defect. A harness configured for Orca that
    never documents it leaves the surface undiscoverable; a harness that
    documents it without being configured for it tells operators to run a tool
    the project never chose.
    """
    surface = str(profile.get("session_surface", "inproc"))
    if surface not in {"inproc", "orca"}:
        errors.append(f"session_surface must be inproc or orca, not {surface!r}")
        return

    contract, skill = session_documentation(payload)
    if not contract:
        return
    # The surface guidance renders wherever the launch procedure renders: in the
    # `harness-session` skill where there is one, in `CLAUDE.md` for a tier with
    # no session tooling. Reading the pair keeps the check indifferent to which.
    text = contract + "\n" + skill
    present = ORCA_SECTION in text

    if surface == "orca":
        if not present:
            errors.append(
                "session_surface is orca but neither CLAUDE.md nor the session "
                f"skill has a {ORCA_SECTION!r} section"
            )
            return
        for clause in ORCA_REQUIRED_CLAUSES:
            if clause not in text:
                errors.append(
                    f"the Orca surface section does not state {clause!r}, which "
                    "the launcher enforces"
                )
    elif present:
        errors.append(
            f"the harness documents {ORCA_SECTION!r} but session_surface is "
            f"{surface!r}"
        )


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("package", type=Path)
    args = parser.parse_args()

    package_arg = args.package.expanduser()
    errors: list[str] = []
    warnings: list[str] = []

    if package_arg.is_symlink():
        errors.append(f"package path may not be a symlink: {package_arg}")
    package = package_arg.resolve()

    required_package = (
        GENERATION_MARKER,
        "payload",
        "project-profile.json",
        "harness-manifest.json",
        "install-harness.sh",
        "README.md",
    )
    for required in required_package:
        if not (package / required).exists():
            errors.append(f"missing {required}")

    if errors:
        for item in errors:
            print(f"ERROR: {item}", file=sys.stderr)
        raise SystemExit(1)

    marker = read_json(package / GENERATION_MARKER, errors, "generation marker")
    if marker.get("generator") != "development-harness":
        errors.append("generation marker does not identify development-harness")

    profile = read_json(package / "project-profile.json", errors, "project-profile.json")
    manifest = read_json(package / "harness-manifest.json", errors, "harness-manifest.json")
    payload = package / "payload"
    if payload.is_symlink() or not payload.is_dir():
        errors.append("payload must be a real directory, not a symlink")

    delegate = str(profile.get("implementation_delegate", "codex-cli")).lower()

    required_payload = [
        "AGENTS.md",
        "CLAUDE.md",
        ".claude/skills/harness-orchestration/SKILL.md",
        ".ai/README.md",
        ".ai/backlog.md",
        ".ai/templates/report.md",
        ".ai/templates/decision.md",
        ".ai/templates/spec.md",
        ".ai/harness/project-profile.json",
        "docs/ai-harness/README.md",
    ]
    tier = str(profile.get("harness_tier", "")).lower()
    mode = str(profile.get("harness_mode", "adopt")).lower()
    greenfield = profile.get("greenfield_context")

    if mode == "create":
        if tier == "fleet":
            errors.append("greenfield create mode may not start at Fleet tier")
        if not isinstance(greenfield, dict):
            errors.append("greenfield create mode requires greenfield_context")
            greenfield = {}
        required_payload += [
            ".ai/project/brief.md",
            ".ai/project/architecture.md",
            ".ai/project/roadmap.md",
            ".ai/project/open-questions.md",
        ]
        if isinstance(greenfield, dict) and greenfield.get("create_root_readme", True):
            required_payload.append("README.md")
        if isinstance(greenfield, dict) and greenfield.get("setup_depth") == "ready-to-build":
            required_payload.append(".ai/specs/current-task.md")
            blocking = greenfield.get("blocking_questions", [])
            if blocking:
                errors.append("ready-to-build greenfield package contains blocking questions")

    if delegate != "claude-only":
        required_payload.append(".claude/skills/harness-codex-delegate/SKILL.md")
    if tier in {"standard", "fleet"}:
        required_payload += [
            ".claude/agents/harness-codebase-researcher.md",
            ".claude/agents/harness-code-reviewer.md",
        ]
    if tier == "fleet":
        if delegate != "codex-cli":
            errors.append("fleet harness requires implementation_delegate=codex-cli")
        required_payload += [
            ".claude/skills/harness-codex-fleet/SKILL.md",
            ".ai/templates/lane-brief.md",
            ".ai/templates/ledger.md",
            "scripts/ai-harness/create-lane-worktree.sh",
        ]
    if str(profile.get("hooks_policy", "")) == "guarded":
        required_payload.append(HOOK_SETTINGS_PATH)
        required_payload += [f"scripts/ai-harness/{name}" for name in HOOK_SCRIPTS]

    required_payload += expected_dynamic_paths(profile, errors)

    for rel in required_payload:
        if not (payload / rel).is_file():
            errors.append(f"missing payload file: {rel}")

    installed_profile = payload / ".ai/harness/project-profile.json"
    if installed_profile.is_file():
        installed_data = read_json(installed_profile, errors, "installed project profile")
        if installed_data != profile:
            errors.append("installed project profile does not match package project-profile.json")

    if mode == "create":
        brief = payload / ".ai/project/brief.md"
        architecture = payload / ".ai/project/architecture.md"
        for path, required_fragment in (
            (brief, "## Problem statement"),
            (architecture, "## Evidence rule"),
        ):
            if path.is_file() and required_fragment not in path.read_text(encoding="utf-8"):
                errors.append(
                    f"greenfield context file missing required section {required_fragment!r}: "
                    f"{path.relative_to(payload).as_posix()}"
                )

    symlinks = [path for path in package.rglob("*") if path.is_symlink()]
    for path in symlinks:
        errors.append(
            "generated package may not contain symlinks: "
            f"{path.relative_to(package).as_posix()}"
        )

    actual_files = {
        path.relative_to(payload).as_posix(): path
        for path in payload.rglob("*")
        if path.is_file() and not path.is_symlink()
    }
    manifest_entries = manifest.get("files", [])
    if not isinstance(manifest_entries, list):
        errors.append("manifest files must be an array")
        manifest_entries = []
    manifest_files: dict[str, dict[str, Any]] = {}
    for index, item in enumerate(manifest_entries):
        if not isinstance(item, dict) or not isinstance(item.get("path"), str):
            errors.append(f"invalid manifest files[{index}] entry")
            continue
        rel = item["path"]
        if rel in manifest_files:
            errors.append(f"duplicate manifest path: {rel}")
        manifest_files[rel] = item

    if set(actual_files) != set(manifest_files):
        absent_manifest = sorted(set(actual_files) - set(manifest_files))
        absent_disk = sorted(set(manifest_files) - set(actual_files))
        if absent_manifest:
            errors.append(f"files absent from manifest: {absent_manifest}")
        if absent_disk:
            errors.append(f"manifest files absent from disk: {absent_disk}")

    component_names: dict[str, str] = {}
    for rel, path in actual_files.items():
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            text = ""
        if text and PLACEHOLDER.search(text):
            errors.append(f"unresolved placeholder in {rel}")

        item = manifest_files.get(rel)
        if item:
            if item.get("sha256") != sha256(path):
                errors.append(f"hash mismatch for {rel}")
            if item.get("bytes") != path.stat().st_size:
                errors.append(f"byte-count mismatch for {rel}")

        if rel.startswith(".claude/skills/") and rel.endswith("/SKILL.md"):
            fm = frontmatter(text)
            if fm is None:
                errors.append(f"skill missing YAML frontmatter: {rel}")
                continue
            for key in ("name", "description"):
                if not fm.get(key):
                    errors.append(f"skill missing {key} frontmatter: {rel}")
            name = str(fm.get("name", ""))
            expected_name = Path(rel).parent.name
            if name and name != expected_name:
                errors.append(f"skill name/path mismatch in {rel}: {name!r} != {expected_name!r}")
            if name in component_names:
                errors.append(f"duplicate Claude component name {name!r}: {component_names[name]} and {rel}")
            elif name:
                component_names[name] = rel

        if rel.startswith(".claude/agents/") and rel.endswith(".md"):
            fm = frontmatter(text)
            if fm is None:
                errors.append(f"agent missing YAML frontmatter: {rel}")
                continue
            for key in ("name", "description"):
                if not fm.get(key):
                    errors.append(f"agent missing {key} frontmatter: {rel}")
            name = str(fm.get("name", ""))
            expected_name = Path(rel).stem
            if name and name != expected_name:
                errors.append(f"agent name/path mismatch in {rel}: {name!r} != {expected_name!r}")
            if name in component_names:
                errors.append(f"duplicate Claude component name {name!r}: {component_names[name]} and {rel}")
            elif name:
                component_names[name] = rel
            if fm.get("permissionMode") == "bypassPermissions":
                errors.append(f"agent defaults to bypassPermissions: {rel}")
            check_declared_tier(rel, text, errors)

        if rel.startswith(".claude/rules/") and rel.endswith(".md"):
            fm = frontmatter(text)
            if fm is None or not fm.get("paths"):
                errors.append(f"scoped rule missing non-empty paths frontmatter: {rel}")

    # Re-check the privilege boundary of profile-generated components so a
    # modified staging package cannot smuggle broader permissions past render.
    for item in profile.get("additional_skills", []):
        if not isinstance(item, dict):
            continue
        name = component_name(item.get("name"))
        rel = f".claude/skills/{name}/SKILL.md"
        path = payload / rel
        if not path.is_file():
            continue
        text = path.read_text(encoding="utf-8")
        fm = frontmatter(text) or {}
        if "allowed-tools" in fm:
            errors.append(f"generated project skill pre-approves tools: {rel}")
        if item.get("manual_only", True) and fm.get("disable-model-invocation") is not True:
            errors.append(f"manual generated project skill is model-invocable: {rel}")

    check_agent_capabilities(profile, payload, errors)
    check_agent_tuning(profile, payload, errors)
    check_launch_line_is_runnable(payload, errors)

    codex_rel = ".claude/skills/harness-codex-delegate/SKILL.md"
    codex_path = payload / codex_rel
    codex_text = codex_path.read_text(encoding="utf-8") if codex_path.is_file() else ""
    if delegate == "claude-only":
        if codex_path.exists():
            errors.append("claude-only harness must omit the Codex delegate skill")
    elif delegate == "codex-plugin":
        for required_fragment in (
            "Configured transport: `codex-plugin`",
            "codex:codex-rescue",
            "openai/codex-plugin-cc",
        ):
            if required_fragment not in codex_text:
                errors.append(
                    f"official Codex plugin delegate missing {required_fragment!r}: {codex_rel}"
                )
    elif delegate == "codex-cli":
        for required_fragment in (
            "Configured transport: `codex-cli`",
            "codex exec",
            '- < "${CLAUDE_PROJECT_DIR}/.ai/specs/current-task.md"',
        ):
            if required_fragment not in codex_text:
                errors.append(
                    f"Codex CLI delegate missing {required_fragment!r}: {codex_rel}"
                )
        if "$(cat" in codex_text:
            errors.append("Codex CLI delegate must pass the spec through stdin, not shell substitution")

    check_line_endings(package, errors)
    check_installer_syntax(package, errors, warnings)

    if tier == "fleet":
        helper = payload / "scripts/ai-harness/create-lane-worktree.sh"
        if helper.is_file() and not (helper.stat().st_mode & 0o111):
            warnings.append("fleet worktree helper is not executable")

    check_hosts(profile, errors)
    check_codex_contract_size(profile, payload, errors, warnings)
    check_codex_skill_mirror(profile, payload, errors)
    check_context_policy(profile, payload, errors, warnings)
    check_important_paths_rule(profile, payload, errors, warnings)
    check_model_invocable_skills(profile, payload, errors, warnings)
    check_session_surface(profile, payload, errors, warnings)
    check_workflows(profile, payload, errors, warnings)
    check_permission_bypass(payload, errors)
    check_session_tools(profile, payload, errors)
    check_hooks(profile, payload, errors, warnings)
    check_read_only_agents_are_not_detached(payload, errors)

    check_always_loaded_size(payload, errors)

    for item in warnings:
        print(f"WARNING: {item}", file=sys.stderr)
    for item in errors:
        print(f"ERROR: {item}", file=sys.stderr)

    if errors:
        raise SystemExit(1)

    print(
        f"OK: {profile.get('project_name')} "
        f"({tier}) with {len(actual_files)} payload files"
    )


if __name__ == "__main__":
    main()
